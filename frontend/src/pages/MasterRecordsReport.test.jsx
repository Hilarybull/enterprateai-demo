import React from "react";
import { afterEach, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
vi.mock("../api/client", () => ({apiRequest:vi.fn(async()=>({})),apiRequestCached:vi.fn(async()=>({})),invalidateWorkspaceCache:vi.fn()}));
vi.mock("html2pdf.js", () => ({ default: vi.fn(() => ({set: vi.fn().mockReturnThis(), from: vi.fn().mockReturnThis(), save: vi.fn().mockResolvedValue(undefined)})) }));
import CataloguePage from "./CataloguePage";
import { useWorkspaceStore } from "../store/workspace";
afterEach(cleanup);
it("includes active employees in the preview and PDF, and lets the owner omit them", async () => {
 const ws={id:"ws-report", name:"Test business", data:{catalogue:{employees:[{id:"e1",name:"Ada <Team>",job_title:"Operations lead",department:"Operations",start_date:"2026-11-24"},{id:"e2",name:"Archived colleague",archived:true}]}}};
 useWorkspaceStore.setState({workspaceId:ws.id,wsDoc:ws,isMemberMode:false,currency:"GBP"});
 render(<MemoryRouter initialEntries={["/catalogue?tab=report"]}><CataloguePage /></MemoryRouter>);
 await screen.findByText("Generate Master records report");
 const checkbox=screen.getByRole("checkbox",{name:"Employees"});
 expect(checkbox.checked).toBe(true);
 fireEvent.click(screen.getByRole("button",{name:"Generate & Preview"}));
 const frame=await screen.findByTitle("Master records report Preview");
 await waitFor(()=>expect(frame.srcdoc).toContain("Ada &lt;Team&gt;"));
 expect(frame.srcdoc).toContain("Operations lead");
 expect(frame.srcdoc).toContain("24/11/2026");
 expect(frame.srcdoc).not.toContain("Archived colleague");
 fireEvent.click(screen.getByRole("button",{name:"Download PDF"}));
 const pdf=(await import("html2pdf.js")).default;
 await waitFor(()=>expect(pdf).toHaveBeenCalled());
 expect(pdf.mock.results[0].value.set.mock.calls[0][0].filename).toMatch(/^master-records-report-/);
 expect(pdf.mock.results[0].value.from.mock.calls[0][0].textContent).toContain("Ada <Team>");
 fireEvent.click(checkbox);
 fireEvent.click(screen.getByRole("button",{name:"Generate & Preview"}));
 expect(screen.getByTitle("Master records report Preview").srcdoc).not.toContain("Ada &lt;Team&gt;");
});
